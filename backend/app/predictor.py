# ============================================================
# FEATURE NAMES
# ============================================================

def get_feature_names():
    """
    Get feature names generated by the fitted preprocessor.
    """

    try:
        names = preprocessor.get_feature_names_out()

        return [
            str(name)
            for name in names
        ]

    except Exception as error:
        print(
            "Could not obtain feature names:",
            error
        )

        return []


def clean_feature_name(feature_name):
    """
    Convert technical preprocessing names into readable names.
    """

    name = str(feature_name)

    name = name.replace(
        "numerical__",
        ""
    )

    name = name.replace(
        "categorical__",
        ""
    )

    replacements = {
        "age_years": "Age",
        "treatment_duration_months": "Treatment duration",
        "distance_to_clinic_km": "Distance to clinic",
        "missed_doses_last_30_days": "Missed doses",
        "followup_attendance": "Follow-up attendance",
        "health_education": "Health education",
        "medication_cost_burden": "Medication cost burden",
        "side_effects": "Side effects",
        "caregiver_support": "Caregiver support",
        "previous_fracture": "Previous fracture",
        "osteoporosis_treatment": "Osteoporosis treatment",
        "sex": "Sex",
        "functional_status": "Functional status",
    }

    for original, replacement in replacements.items():
        name = name.replace(
            original,
            replacement
        )

    name = name.replace(
        "_",
        " "
    )

    return name


# ============================================================
# BUILD SHAP BACKGROUND
# ============================================================

def build_shap_background():
    """
    Load the original training dataset and transform a
    representative sample using the same preprocessor used
    by the trained models.

    The target variable is removed so that it cannot leak into
    the explanation.
    """

    if not os.path.exists(DATASET_PATH):
        print(
            "SHAP background dataset not found:",
            DATASET_PATH
        )

        return None

    try:
        dataset = pd.read_csv(
            DATASET_PATH
        )

        # Remove target and possible leakage column.
        columns_to_drop = [
            "adherence",
            "adherence_score",
        ]

        feature_columns = [
            column
            for column in dataset.columns
            if column not in columns_to_drop
        ]

        background_data = dataset[
            feature_columns
        ].copy()

        # Use a deterministic representative sample.
        # This keeps prediction requests reasonably fast.
        sample_size = min(
            50,
            len(background_data)
        )

        background_data = background_data.sample(
            n=sample_size,
            random_state=42
        )

        processed_background = preprocessor.transform(
            background_data
        )

        return np.asarray(
            processed_background,
            dtype=float
        )

    except Exception as error:
        print(
            "Could not build SHAP background:",
            error
        )

        return None


# Build the SHAP background once when the backend starts.
SHAP_BACKGROUND = build_shap_background()


# ============================================================
# SHAP SVM EXPLAINER
# ============================================================

_svm_shap_explainer = None


def get_svm_shap_explainer():
    """
    Create and cache the Kernel SHAP explainer for the calibrated
    SVM.
    """

    global _svm_shap_explainer

    if shap is None:
        return None

    if SHAP_BACKGROUND is None:
        return None

    if _svm_shap_explainer is not None:
        return _svm_shap_explainer

    try:

        svm_model = models[
            "support_vector_machine"
        ]

        def svm_probability(data):
            data = np.asarray(
                data,
                dtype=float
            )

            probabilities = svm_model.predict_proba(
                data
            )

            # Class 1 = Adherent
            return probabilities[:, 1]

        _svm_shap_explainer = shap.KernelExplainer(
            svm_probability,
            SHAP_BACKGROUND
        )

        return _svm_shap_explainer

    except Exception as error:

        print(
            "Could not create SVM SHAP explainer:",
            error
        )

        return None


# ============================================================
# BUILD FEATURE EXPLANATIONS
# ============================================================

def build_feature_explanations(
    feature_names,
    contributions,
    method,
    top_n=5
):
    """
    Convert SHAP values into the API explanation format.
    """

    contributions = np.asarray(
        contributions,
        dtype=float
    ).flatten()

    explanations = []

    count = min(
        len(feature_names),
        len(contributions)
    )

    for index in range(count):

        value = float(
            contributions[index]
        )

        if abs(value) <= 0:
            continue

        direction = (
            "increases"
            if value >= 0
            else "decreases"
        )

        explanations.append(
            {
                "feature": clean_feature_name(
                    feature_names[index]
                ),

                "contribution": round(
                    abs(value),
                    4
                ),

                "direction": direction,

                "method": method
            }
        )

    explanations.sort(
        key=lambda item: item["contribution"],
        reverse=True
    )

    return explanations[:top_n]


# ============================================================
# LOGISTIC REGRESSION EXPLANATION
# ============================================================

def explain_logistic_regression(
    model,
    processed_data,
    feature_names
):

    try:

        coefficients = np.asarray(
            model.coef_[0],
            dtype=float
        )

        values = np.asarray(
            processed_data,
            dtype=float
        ).flatten()

        contributions = (
            coefficients * values
        )

        return build_feature_explanations(
            feature_names,
            contributions,
            "SHAP-compatible linear explanation"
        )

    except Exception as error:

        print(
            "Logistic Regression explanation failed:",
            error
        )

        return []


# ============================================================
# GRADIENT BOOSTING SHAP
# ============================================================

def explain_gradient_boosting(
    model,
    processed_data,
    feature_names
):

    if shap is None:
        return []

    try:

        explainer = shap.TreeExplainer(
            model
        )

        shap_values = explainer.shap_values(
            processed_data
        )

        if isinstance(
            shap_values,
            list
        ):

            if len(shap_values) == 2:
                values = np.asarray(
                    shap_values[1]
                ).flatten()
            else:
                values = np.asarray(
                    shap_values[0]
                ).flatten()

        else:

            values = np.asarray(
                shap_values
            )

            if values.ndim == 2:
                values = values[0]

            values = values.flatten()

        return build_feature_explanations(
            feature_names,
            values,
            "SHAP"
        )

    except Exception as error:

        print(
            "Gradient Boosting SHAP explanation failed:",
            error
        )

        return []


# ============================================================
# SUPPORT VECTOR MACHINE SHAP
# ============================================================

def explain_svm(
    processed_data,
    feature_names
):

    if shap is None:
        return []

    explainer = get_svm_shap_explainer()

    if explainer is None:
        return []

    try:

        shap_values = explainer.shap_values(
            processed_data,
            nsamples=100
        )

        values = np.asarray(
            shap_values
        )

        if values.ndim > 1:
            values = values[0]

        values = values.flatten()

        return build_feature_explanations(
            feature_names,
            values,
            "SHAP"
        )

    except Exception as error:

        print(
            "SVM SHAP explanation failed:",
            error
        )

        return []


# ============================================================
# FALLBACK EXPLANATION
# ============================================================

def get_fallback_explanation(
    model,
    processed_data,
    feature_names
):

    try:

        if hasattr(
            model,
            "feature_importances_"
        ):

            importances = np.asarray(
                model.feature_importances_
            )

            return build_feature_explanations(
                feature_names,
                importances,
                "Feature importance"
            )

        if hasattr(
            model,
            "coef_"
        ):

            coefficients = np.asarray(
                model.coef_[0]
            )

            return build_feature_explanations(
                feature_names,
                coefficients,
                "Coefficient-based explanation"
            )

    except Exception as error:

        print(
            "Fallback explanation failed:",
            error
        )

    return []


# ============================================================
# INTERPRETABILITY ROUTER
# ============================================================

def get_interpretability(
    model,
    model_key,
    processed_data,
    feature_names
):

    explanations = []

    method = "Unavailable"

    # --------------------------------------------------------
    # Logistic Regression
    # --------------------------------------------------------

    if model_key == "logistic_regression":

        explanations = explain_logistic_regression(
            model,
            processed_data,
            feature_names
        )

        if explanations:
            method = (
                "SHAP-compatible linear explanation"
            )

    # --------------------------------------------------------
    # SVM
    # --------------------------------------------------------

    elif model_key == "support_vector_machine":

        explanations = explain_svm(
            processed_data,
            feature_names
        )

        if explanations:
            method = "SHAP"

    # --------------------------------------------------------
    # Gradient Boosting
    # --------------------------------------------------------

    elif model_key == "gradient_boosting":

        explanations = explain_gradient_boosting(
            model,
            processed_data,
            feature_names
        )

        if explanations:
            method = "SHAP"

    # --------------------------------------------------------
    # Fallback
    # --------------------------------------------------------

    if not explanations:

        explanations = get_fallback_explanation(
            model,
            processed_data,
            feature_names
        )

        if explanations:
            method = explanations[0]["method"]

    return {
        "method": method,
        "top_features": explanations
    }


# ============================================================
# PREDICT WITH ONE MODEL
# ============================================================

def predict_with_model(
    data: dict,
    model_key: str
):

    if model_key not in models:

        raise ValueError(
            f"Unknown model: {model_key}"
        )

    # --------------------------------------------------------
    # Create input DataFrame
    # --------------------------------------------------------

    input_data = pd.DataFrame(
        [data]
    )

    # --------------------------------------------------------
    # Apply trained preprocessing
    # --------------------------------------------------------

    processed_data = preprocessor.transform(
        input_data
    )

    # --------------------------------------------------------
    # Get model
    # --------------------------------------------------------

    model = models[
        model_key
    ]

    # --------------------------------------------------------
    # Prediction
    # --------------------------------------------------------

    prediction = model.predict(
        processed_data
    )[0]

    # --------------------------------------------------------
    # Probability
    # --------------------------------------------------------

    probabilities = model.predict_proba(
        processed_data
    )[0]

    probability_non_adherent = float(
        probabilities[0]
    )

    probability_adherent = float(
        probabilities[1]
    )

    # --------------------------------------------------------
    # Label
    # --------------------------------------------------------

    if prediction == 1:

        prediction_label = "Adherent"

    else:

        prediction_label = "Non-adherent"

    # --------------------------------------------------------
    # Feature names
    # --------------------------------------------------------

    feature_names = get_feature_names()

    # --------------------------------------------------------
    # Interpretability
    # --------------------------------------------------------

    interpretability = get_interpretability(
        model,
        model_key,
        processed_data,
        feature_names
    )

    # --------------------------------------------------------
    # Response
    # --------------------------------------------------------

    return {

        "model": model_names[
            model_key
        ],

        "prediction": prediction_label,

        "probability_adherent": round(
            probability_adherent,
            4
        ),

        "probability_non_adherent": round(
            probability_non_adherent,
            4
        ),

        "interpretability": interpretability
    }


# ============================================================
# PREDICT WITH ALL MODELS
# ============================================================

def predict_all_models(
    data: dict
):

    results = {}

    for model_key in models:

        results[model_key] = predict_with_model(
            data,
            model_key
        )

    return results